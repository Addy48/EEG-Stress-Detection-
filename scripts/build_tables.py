"""Rebuild the baseline and ensemble tables from the saved result files in results/.

    python scripts/build_tables.py            # writes results/TABLES.md and prints it

Nothing is re-trained. Every number comes from a saved metrics file; SD Arithmetic
has no valid detailed export and is read from the aggregate summary (marked with a dagger).
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
MODELS = ["KNN", "RandomForest", "XGBoost", "CatBoost", "AdaBoost", "LinearSVC", "LogisticRegression"]
TASKS = ["Relax-Arithmetic", "Relax-Mirror", "Relax-Stroop"]
SHORT = {"Relax-Arithmetic": "Arith", "Relax-Mirror": "Mirror", "Relax-Stroop": "Stroop"}


def detailed(folder: str, model: str, task: str):
    path = RES / folder / model / task / "metrics.csv"
    return float(pd.read_csv(path)["Accuracy"].iloc[0]) * 100 if path.exists() else None


def aggregate(file: str, model: str, task: str) -> float:
    df = pd.read_csv(RES / "aggregates" / file).set_index("Model")
    return float(df.loc[model, task])


def baseline_table() -> pd.DataFrame:
    rows = []
    for model in MODELS:
        row = {"Model": model}
        sd, si = [], []
        for task in TASKS:
            v = detailed("sd_baseline", model, task)
            mark = ""
            if v is None:
                v, mark = aggregate("SubjectDependent_AllModels.csv", model, task), "†"
            row[f"SD {SHORT[task]}"] = f"{v:.2f}{mark}"
            sd.append(v)
        row["SD avg"] = f"{sum(round(v, 2) for v in sd) / 3:.2f}"
        for task in TASKS:
            v = detailed("si_baseline", model, task)
            row[f"SI {SHORT[task]}"] = f"{v:.2f}"
            si.append(v)
        row["SI avg"] = f"{sum(round(v, 2) for v in si) / 3:.2f}"
        rows.append(row)
    return pd.DataFrame(rows)


def ensemble_table() -> tuple[pd.DataFrame, list]:
    files = {
        ("Voting", "SD"): RES / "ensembles" / "Voting_SubjectDependent.csv",
        ("Voting", "SI"): RES / "ensembles" / "Voting_SubjectIndependent.csv",
        ("Bagging", "SD"): RES / "ensembles" / "Bagging_SubjectDependent.csv",
        ("Bagging", "SI"): RES / "ensembles" / "Bagging_SubjectIndependent.csv",
        ("Stacking", "SD"): RES / "ensembles" / "Stacking_SubjectDependent.csv",
    }
    rows = []
    for (method, protocol), path in files.items():
        df = pd.read_csv(path).set_index("Task")["Accuracy"] * 100
        rows.append({"Method": method, "Protocol": protocol, **{SHORT[t]: f"{df[t]:.2f}" for t in TASKS}, "Avg": f"{sum(round(df[t], 2) for t in TASKS) / 3:.2f}"})
    stacking_si = {}
    for path in (RES / "ensembles" / "stacking_si").glob("*MetaEnsemble.csv"):
        d = pd.read_csv(path)
        stacking_si[d["Task"].iloc[0]] = float(d["Accuracy"].mean()) * 100
    rows.append({"Method": "Stacking", "Protocol": "SI", **{SHORT[t]: f"{stacking_si[t]:.2f}" for t in TASKS},
                 "Avg": f"{sum(round(stacking_si[t], 2) for t in TASKS) / 3:.2f}"})
    return pd.DataFrame(rows), []


def si_per_class() -> pd.DataFrame:
    rows = []
    for model in MODELS:
        for task in TASKS:
            rep = pd.read_csv(RES / "si_baseline" / model / task / "classification_report.csv", index_col=0)
            rows.append({
                "Model": model, "Task": task,
                "Relax P": rep.loc["Relax", "precision"], "Relax R": rep.loc["Relax", "recall"], "Relax F1": rep.loc["Relax", "f1-score"],
                "Task P": rep.loc["Task", "precision"], "Task R": rep.loc["Task", "recall"], "Task F1": rep.loc["Task", "f1-score"],
                "Support/class": int(rep.loc["Relax", "support"]),
            })
    return pd.DataFrame(rows)


def main() -> None:
    base = baseline_table()
    ens, _ = ensemble_table()
    pc = si_per_class()
    out = [
        "# Tables rebuilt from the saved result files",
        "",
        "Accuracy in %, mean over five folds; the average column is the mean of the three rounded task values, as in the manuscript. Generated by `scripts/build_tables.py`; nothing here was re-trained.",
        "",
        "## Baselines (manuscript Table 1)",
        "",
        base.to_markdown(index=False),
        "",
        "† SD Arithmetic has no valid detailed export; the value comes from `results/aggregates/SubjectDependent_AllModels.csv`.",
        "SI is the five-fold *file-group* evaluation described in `docs/PROVENANCE.md`, not a confirmed person-held-out estimate.",
        "",
        "## Ensembles (manuscript Table 2)",
        "",
        ens.to_markdown(index=False),
        "",
        "Stacking under SI comes from the per-fold files in `results/ensembles/stacking_si/`.",
        "",
        "## SI per-class metrics (pooled held-out predictions, 384,000 rows per class)",
        "",
        pc.round(4).to_markdown(index=False),
        "",
    ]
    text = "\n".join(out)
    (RES / "TABLES.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
